#include "build.h"
static void compact_seed(const char *input, const char *output) {
    char parent[PATH_MAX];
    strcpy(parent, output);
    *strrchr(parent, '/') = 0;
    b_mkdir(parent);
    FILE *in = fopen(input, "rb"), *out = fopen(output, "wb");
    if (!in || !out) b_die("cannot open bootstrap snapshot");
    fputs("/* Generated by ./builder snapshot; edit NanoC sources instead. */\n", out);
    char *line = NULL;
    size_t capacity = 0, column = 0;
    bool directive = false;
    ssize_t length;
    while ((length = getline(&line, &capacity, in)) >= 0) {
        if (!strncmp(line, "#line ", 6)) continue;
        while (length && (line[length - 1] == '\n' || line[length - 1] == '\r')) line[--length] = 0;
        if (!length) continue;
        if (*line == '#' || directive) {
            if (column) { fputc('\n', out); column = 0; }
            fprintf(out, "%s\n", line);
            directive = line[length - 1] == '\\';
        } else {
            if (column) fputc(' ', out);
            fputs(line, out);
            column += (size_t)length + 1;
            if (column >= 512) { fputc('\n', out); column = 0; }
        }
    }
    if (column) fputc('\n', out);
    free(line);
    bool bad = ferror(in) || ferror(out);
    if (fclose(in)) bad = true;
    if (fclose(out)) bad = true;
    if (bad) b_die("cannot write bootstrap snapshot");
}
void b_snapshot(void) {
    BPaths sources = {0}, headers = {0};
    b_walk(&sources, "src", ".nc");
    b_walk(&headers, "include", ".h");
    b_remove("bootstrap/src");
    b_remove("bootstrap/include");
    for (size_t i = 0; i < sources.n; ++i) {
        char generated[PATH_MAX], target[PATH_MAX];
        b_path(generated, "build/stage3", sources.v[i]);
        strcpy(generated + strlen(generated) - 2, "c");
        b_path(target, "bootstrap", sources.v[i]);
        strcpy(target + strlen(target) - 2, "c");
        compact_seed(generated, target);
    }
    for (size_t i = 0; i < headers.n; ++i) {
        char target[PATH_MAX];
        b_path(target, "bootstrap", headers.v[i]);
        b_copy(headers.v[i], target);
    }
    b_paths_free(&sources);
    b_paths_free(&headers);
    puts("Refreshed generated C bootstrap and its frozen headers");
}
