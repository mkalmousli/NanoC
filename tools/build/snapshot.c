#include "build.h"
static void readable(const char *source, const char *target) {
    char dir[PATH_MAX];
    strcpy(dir, target);
    *strrchr(dir, '/') = 0;
    b_mkdir(dir);
    FILE *in = fopen(source, "rb"), *out = fopen(target, "wb");
    if (!in || !out) b_die("cannot open bootstrap snapshot");
    fputs("/* Generated by ./builder snapshot; edit NanoC sources instead. */\n", out);
    char *line = NULL;
    size_t cap = 0, depth = 0;
    ssize_t n;
    while ((n = getline(&line, &cap, in)) >= 0) {
        if (!strncmp(line, "#line ", 6)) continue;
        char *s = line;
        while (*s == ' ' || *s == '\t') ++s;
        if (!*s || *s == '\n') continue;
        if (*s == '#') { fputs(s, out); continue; }
        size_t len = strlen(s);
        while (len && (s[len-1]=='\n'||s[len-1]=='\r')) s[--len]=0;
        bool close = *s == '}';
        bool function = len && s[len - 1] == '{' && strchr(s, '(') &&
            strncmp(s, "if ", 3) && strncmp(s, "for ", 4) && strncmp(s, "while ", 6);
        if (function) depth = 0;
        bool trailing = len && s[len - 1] == '}' && !close;
        if (close && depth) --depth;
        fprintf(out, "%*s", (int)(depth * 4), "");
        bool block = len && s[len - 1] == '{' &&
            (!strncmp(s, "if ", 3) || !strncmp(s, "for ", 4) ||
             !strncmp(s, "while ", 6) || !strncmp(s, "else", 4) ||
             (strchr(s, '(') && !strchr(s, '=') && strncmp(s, "return ", 7)));
        if (block) { s[len - 1] = 0; fprintf(out, "%s{\n", s); ++depth; }
        else if (trailing) {
            s[len - 1] = 0;
            fprintf(out, "%s\n%*s}\n", s, (int)((depth ? depth - 1 : 0) * 4), "");
            if (depth) --depth;
        } else fprintf(out, "%s\n", s);
    }
    free(line);
    bool bad=ferror(in)||ferror(out);
    if(fclose(in))bad=true;
    if(fclose(out))bad=true;
    if(bad)b_die("bootstrap snapshot write failed");
}
void b_snapshot(void) {
    BPaths sources={0},headers={0};
    b_walk(&sources,"src",".nc"); b_walk(&headers,"build/include",".h");
    b_remove("bootstrap/src"); b_remove("bootstrap/include");
    for(size_t i=0;i<sources.n;++i){char a[PATH_MAX],b[PATH_MAX];
        b_path(a,"build/stage3",sources.v[i]);strcpy(a+strlen(a)-2,"c");
        b_path(b,"bootstrap",sources.v[i]);strcpy(b+strlen(b)-2,"c");readable(a,b);}
    for(size_t i=0;i<headers.n;++i){char b[PATH_MAX];b_path(b,"bootstrap",headers.v[i]+6);b_copy(headers.v[i],b);}
    b_paths_free(&sources);b_paths_free(&headers);puts("Refreshed readable C bootstrap");
}
